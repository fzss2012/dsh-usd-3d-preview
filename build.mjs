/**
 * Build both halves of the plugin into `lib/`.
 *
 * Why a hand-written wrapper instead of the repository's own `tsdown` pipeline:
 * this package is installed from a directory rather than built inside the dsh
 * workspace, so it has no access to the workspace-level `tsdown.client.ts`. Both
 * output formats are small and stable, and this script reproduces them exactly:
 *
 *   lib/index.js   ESM for the host loader — node builtins stay external, the
 *                  plugin's own modules are bundled, so the half has no
 *                  resolvable dependency on the profile's node_modules.
 *   lib/client.js  the shell's classic-CJS module-table entry:
 *                  `window.__ModuleLoader__.load({ id, factory })`.
 *
 * `react` and `react/jsx-runtime` stay external in the browser bundle because
 * the shell seeds them in the platform module table (`PLATFORM_MODULES`); three
 * and its USD loaders are bundled, because nothing in that table supplies them
 * and a plugin may not add a seed word. The `dsh.client.platform` field in
 * package.json is what makes the host serve the client bundle at all.
 */
import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const sha256 = () => createHash('sha256')

const root = dirname(fileURLToPath(import.meta.url))
const lib = join(root, 'lib')
const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

/** Indent every non-empty line, so the generated wrapper stays readable. */
const indent = (text, pad) => text
  .split('\n')
  .map(line => (line === '' ? line : pad + line))
  .join('\n')

/** Report one artifact's size. */
const report = (name, text) => process.stdout.write(
  `${name}  ${(Buffer.byteLength(text) / 1024).toFixed(1)} KiB\n`,
)

await mkdir(lib, { recursive: true })

// ── engine assets: worker bundle + WASM binary, embedded as base64 ──────────
// A client plugin ships as one module-table entry; there is no host route it can
// assume for two extra files. Both travel inside the bundle and become blob URLs
// at first use. The generated module is content-addressed, so an unchanged
// engine does not rewrite the source file (and does not disturb HMR).
const engineDir = join(root, 'node_modules', '@huggingface', 'usd-web-viewer')
const generatedPath = join(root, 'src/client/engine-assets.generated.js')
const workerBundle = await build({
  entryPoints: [join(engineDir, 'dist/esm/worker.js')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'browser',
  target: 'chrome120',
  legalComments: 'none',
  logLevel: 'warning',
  plugins: [patchEngineTransport()],
})
const workerText = workerBundle.outputFiles[0].text
const wasmBytes = await readFile(join(engineDir, 'dist/wasm/usd_wasm_bg.wasm'))
const digest = sha256().update(workerText).update(wasmBytes).digest('hex').slice(0, 16)
const generation = `/**
 * OpenUSD engine assets, embedded at build time by build.mjs — do not edit.
 *
 * worker: the engine's Web Worker, bundled (it imports the wasm-bindgen glue).
 * wasm:   \`usd_wasm_bg.wasm\` from @huggingface/usd-web-viewer ${JSON.parse(
   await readFile(join(engineDir, 'package.json'), 'utf8')).version}.
 * digest: ${digest} (sha256 of worker text + wasm bytes, first 16 hex chars).
 */
export const ENGINE_ASSETS = {
  wasmBytes: ${wasmBytes.byteLength},
  workerBytes: ${Buffer.byteLength(workerText)},
  digest: ${JSON.stringify(digest)},
  wasm: ${JSON.stringify(wasmBytes.toString('base64'))},
  worker: ${JSON.stringify(Buffer.from(workerText, 'utf8').toString('base64'))},
}
`
const previous = await readFile(generatedPath, 'utf8').catch(() => '')
if (!previous.includes(`digest: ${JSON.stringify(digest)}`)) {
  await writeFile(generatedPath, generation, 'utf8')
  process.stdout.write(`engine-assets.generated.js  regenerated (${digest})\n`)
} else {
  process.stdout.write(`engine-assets.generated.js  unchanged (${digest})\n`)
}

// ── host half ───────────────────────────────────────────────────────────────
const host = await build({
  entryPoints: [join(root, 'src/host/index.js')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  legalComments: 'inline',
  logLevel: 'warning',
  banner: { js: '/* dsh-usd-3d-preview host half: generated by build.mjs from src/host — do not edit. */' },
})
report('lib/index.js', host.outputFiles[0].text)
await writeFile(join(lib, 'index.js'), host.outputFiles[0].text, 'utf8')

// ── engine transport patch ──────────────────────────────────────────────────
/**
 * Teach the engine's asset transport about `s3://`.
 *
 * `requestFor()` (in `@huggingface/usd-web-viewer/dist/esm/load-core.js`, which the
 * worker bundle inlines) picks a transport from the asset URL's scheme:
 *
 *     if (protocol === LOCAL && rootUrl.startsWith(LOCAL)) return localResponse(files, url)
 *     if (url !== rootUrl && protocol !== 'http:' && protocol !== 'https:') throw TypeError
 *
 * The `files` package table is wired into the `local:` arm only, so a crate's
 * absolute `s3://bucket/...` reference throws **before** a package key is looked
 * up — no key spelling can satisfy it. That is why a stage composes only the
 * layers whose references are relative or that this plugin rewrote itself.
 *
 * The patch adds the missing arm: `s3:` URLs are fetched through the host half's
 * signed asset route (see `src/host/index.js`), which is same-origin from the
 * worker. Nothing else changes, and a build against an engine whose `requestFor`
 * moved fails loudly instead of shipping a silent no-op.
 */
// A function declaration, not a const: the worker build above runs before this
// point in the file and must still be able to use the plugin.
function patchEngineTransport() {
  const assetRoute = '/usd-preview/asset'
  return {
    name: 'usd-engine-s3-transport',
    setup(context) {
      context.onLoad({ filter: /load-core\.js$/ }, async (args) => {
        const source = await readFile(args.path, 'utf8')
        const anchor = 'export function requestFor(rootUrl, files) {\n'
          + '    return async (url) => {\n'
          + '        const { protocol } = new URL(url);\n'
        if (!source.includes(anchor)) {
          throw new Error('load-core.js: the requestFor() anchor changed — update patchEngineTransport in build.mjs')
        }
        const arm = [
          '        if (protocol === "s3:") {',
          '            // Object-storage layer: the host half signs the read.',
          `            const target = new URL(${JSON.stringify(assetRoute)}, self.location.origin);`,
          '            target.searchParams.set("uri", url);',
          '            return fetch(target.href, {',
          '                credentials: "same-origin",',
          '                referrerPolicy: "no-referrer",',
          '                headers: { "x-dsh-usd-preview": "asset" },',
          '            });',
          '        }',
          '',
        ].join('\n')
        return { contents: source.replace(anchor, anchor + arm), loader: 'js' }
      })
    },
  }
}

// ── browser half ────────────────────────────────────────────────────────────
const client = await build({
  entryPoints: [join(root, 'src/client/index.jsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'chrome120',
  jsx: 'automatic',
  // The platform module table's seed words. Anything else must be bundled.
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  plugins: [patchEngineTransport()],
  legalComments: 'inline',
  logLevel: 'warning',
  banner: { js: '/* dsh-usd-3d-preview: generated by build.mjs from src/client — do not edit this file. */' },
})
const wrapped = `window.__ModuleLoader__.load({
\tid: ${JSON.stringify(manifest.name)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${indent(client.outputFiles[0].text, '\t\t')}
\t\t// esbuild's CJS emit replaces module.exports; the runtime checks the tag on what it receives.
\t\tvar bundleExports = module.exports;
\t\tif (bundleExports !== exports) Object.defineProperty(bundleExports, Symbol.toStringTag, { value: "Module" });
\t\treturn bundleExports;
\t}
});
`
report('lib/client.js', wrapped)
await writeFile(join(lib, 'client.js'), wrapped, 'utf8')
